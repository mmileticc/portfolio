/**
 * Generates the content the app imports at build time:
 *   src/app/content/generated/posts.ts   blog posts from content/blog/*.md
 *   src/app/content/generated/github.ts  repositories and latest commits
 *   public/sitemap.xml, public/robots.txt, public/rss.xml
 *
 * Runs with Node's built-in TypeScript support: `node scripts/build-content.ts`.
 * Set GITHUB_TOKEN to raise the API rate limit (the deploy workflow does).
 */
import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import matter from 'gray-matter';
import { Marked } from 'marked';
import { createHighlighter } from 'shiki';
import { fetchGithubSnapshot } from '../src/app/content/github-api.ts';
import { PROJECTS } from '../src/app/content/projects.ts';
import { SITE } from '../src/app/site.config.ts';
import type { GithubSnapshot, Post } from '../src/app/content/types.ts';

const ROOT = join(import.meta.dirname, '..');
const BLOG_DIR = join(ROOT, 'content', 'blog');
const OUT_DIR = join(ROOT, 'src', 'app', 'content', 'generated');
const PUBLIC_DIR = join(ROOT, 'public');
const offline = process.argv.includes('--offline');

mkdirSync(OUT_DIR, { recursive: true });

/* ───────── Blog ───────── */

const LANGS = ['ts', 'js', 'kotlin', 'java', 'bash', 'json', 'html', 'scss', 'css', 'cpp'];
const highlighter = await createHighlighter({
  themes: ['github-light', 'github-dark'],
  langs: LANGS,
});

const marked = new Marked({
  gfm: true,
  renderer: {
    code({ text, lang }) {
      const language = lang && LANGS.includes(lang) ? lang : 'text';
      return highlighter.codeToHtml(text, {
        lang: language,
        themes: { light: 'github-light', dark: 'github-dark' },
        defaultColor: false,
      });
    },
    link({ href, text }) {
      const external = /^https?:\/\//.test(href);
      // Site paths like "/projects/goth" become relative so they resolve against <base href>,
      // which is "/portfolio/" on GitHub Pages.
      const local = href.startsWith('/') ? href.slice(1) || './' : href;
      return external
        ? `<a href="${href}" target="_blank" rel="noopener">${text}</a>`
        : `<a href="${local}">${text}</a>`;
    },
  },
});

function toIsoDate(value: unknown): string {
  if (value instanceof Date) return value.toISOString().slice(0, 10);
  return String(value);
}

export function parsePost(slug: string, source: string): Post & { draft: boolean } {
  const { data, content } = matter(source);
  if (!data['title'] || !data['date']) {
    throw new Error(`content/blog/${slug}.md needs "title" and "date" in its front matter`);
  }
  const words = content.split(/\s+/).filter(Boolean).length;
  return {
    slug,
    title: String(data['title']),
    date: toIsoDate(data['date']),
    summary: String(data['summary'] ?? ''),
    tags: Array.isArray(data['tags']) ? data['tags'].map(String) : [],
    readingMinutes: Math.max(1, Math.round(words / 220)),
    html: marked.parse(content, { async: false }),
    draft: data['draft'] === true,
  };
}

const posts: Post[] = existsSync(BLOG_DIR)
  ? readdirSync(BLOG_DIR)
      .filter((f) => f.endsWith('.md'))
      .map((f) => parsePost(f.replace(/\.md$/, ''), readFileSync(join(BLOG_DIR, f), 'utf8')))
      .filter((p) => !p.draft)
      .map(({ draft: _draft, ...post }) => post)
      .sort((a, b) => b.date.localeCompare(a.date))
  : [];

writeFileSync(
  join(OUT_DIR, 'posts.ts'),
  `// Generated by scripts/build-content.ts. Do not edit.\n` +
    `import type { Post } from '../types';\n\n` +
    `export const POSTS: Post[] = ${JSON.stringify(posts, null, 2)};\n`,
);
console.log(`✔ ${posts.length} blog post(s)`);

/* ───────── GitHub ───────── */

const githubFile = join(OUT_DIR, 'github.ts');
const empty: GithubSnapshot = { fetchedAt: '', repos: [], commits: [] };
let snapshot: GithubSnapshot | null = null;

if (!offline) {
  try {
    const token = process.env['GITHUB_TOKEN'];
    snapshot = await fetchGithubSnapshot(
      SITE.githubUser,
      token ? { Authorization: `Bearer ${token}` } : {},
    );
    console.log(`✔ ${snapshot.repos.length} repos, ${snapshot.commits.length} recent commits`);
  } catch (err) {
    console.warn(`⚠ GitHub fetch failed (${(err as Error).message}).`);
  }
}

if (snapshot || !existsSync(githubFile)) {
  writeFileSync(
    githubFile,
    `// Generated by scripts/build-content.ts. Do not edit.\n` +
      `import type { GithubSnapshot } from '../types';\n\n` +
      `export const GITHUB_SNAPSHOT: GithubSnapshot = ${JSON.stringify(snapshot ?? empty, null, 2)};\n`,
  );
} else {
  console.log('  Keeping the previous GitHub snapshot.');
}

/* ───────── Sitemap ───────── */

const routes = [
  '/',
  '/projects',
  ...PROJECTS.map((p) => `/projects/${p.slug}`),
  '/about',
  '/blog',
  ...posts.map((p) => `/blog/${p.slug}`),
  '/contact',
];

writeFileSync(
  join(PUBLIC_DIR, 'sitemap.xml'),
  `<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n` +
    routes
      .map((r) => `  <url><loc>${SITE.url}${r === '/' ? '/' : `${r}/`}</loc></url>`)
      .join('\n') +
    `\n</urlset>\n`,
);
writeFileSync(
  join(PUBLIC_DIR, 'robots.txt'),
  `User-agent: *\nAllow: /\n\nSitemap: ${SITE.url}/sitemap.xml\n`,
);
console.log(`✔ sitemap with ${routes.length} routes`);

/* ───────── RSS ───────── */

const xml = (text: string) =>
  text.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');

writeFileSync(
  join(PUBLIC_DIR, 'rss.xml'),
  `<?xml version="1.0" encoding="UTF-8"?>
<rss version="2.0" xmlns:atom="http://www.w3.org/2005/Atom">
  <channel>
    <title>${xml(SITE.name)} · Setlist</title>
    <link>${SITE.url}/blog/</link>
    <atom:link href="${SITE.url}/rss.xml" rel="self" type="application/rss+xml" />
    <description>Notes on Kotlin, Android, Angular and the things I build.</description>
    <language>en</language>
${posts
  .map(
    (p) => `    <item>
      <title>${xml(p.title)}</title>
      <link>${SITE.url}/blog/${p.slug}/</link>
      <guid>${SITE.url}/blog/${p.slug}/</guid>
      <pubDate>${new Date(`${p.date}T12:00:00Z`).toUTCString()}</pubDate>
      <description>${xml(p.summary)}</description>
    </item>`,
  )
  .join('\n')}
  </channel>
</rss>
`,
);
console.log(`✔ rss with ${posts.length} item(s)`);
